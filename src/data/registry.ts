export function getComponentBySlug(slug: string): RegistryComponent | undefined {
  return REGISTRY_COMPONENTS.find(c => c.slug === slug);
}

export function getComponentNeighbors(slug: string): { prev?: RegistryComponent; next?: RegistryComponent } {
  const index = REGISTRY_COMPONENTS.findIndex(c => c.slug === slug);
  if (index === -1) return {};
  return {
    prev: index > 0 ? REGISTRY_COMPONENTS[index - 1] : undefined,
    next: index < REGISTRY_COMPONENTS.length - 1 ? REGISTRY_COMPONENTS[index + 1] : undefined,
  };
}
